    fun buildCompleteSurahList(predefined: List<Surah>): List<Surah> {
        val predefinedMap = predefined.associateBy { it.id }
        
        return surahMetadata.map { meta ->
            predefinedMap[meta.id] ?: generateSurahFallback(meta)
        }
    }

    private fun generateSurahFallback(meta: SurahMeta): Surah {
        return Surah(
            id = meta.id,
            name = "${meta.name} Suresi",
            revelationOrder = meta.revelationOrder,
            revelationPlace = meta.revelationPlace,
            verseCount = meta.verseCount,
            verses = emptyList() // indicates it needs to be fetched
        )
    }
